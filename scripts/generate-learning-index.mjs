import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { loadTsModule } from "../tests/unit/load-ts-module.mjs"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const { STARTER_LESSONS } = await loadTsModule("src/data/lessons.ts")
const { grammarData } = await loadTsModule("src/data/grammar-data.ts")
const vocabulary = []
for (const level of ["survival", "daily", "fluent"]) {
  const data = await loadTsModule(`src/data/vocabulary/${level}.ts`)
  vocabulary.push(...data[`${level}Vocab`])
}
const summaries = STARTER_LESSONS.map(({ steps, ...lesson }) => ({ ...lesson, practiceCount: steps.filter(step => "itemId" in step).length }))
const lookup = {}
for (const lesson of STARTER_LESSONS) {
  lookup[`lesson:${lesson.id}`] = [lesson.title, `/learn/${lesson.id}`]
  for (const step of lesson.steps) {
    if (!("itemId" in step)) continue
    const key = `${step.itemType}:${step.itemId}`
    lookup[key] ??= [step.answer || step.title, `/learn/${lesson.id}`]
  }
}
for (const point of Object.values(grammarData).flat()) lookup[`grammar:${point.id}`] = [point.title, `/grammar?level=${point.level}&item=${encodeURIComponent(point.id)}`]
for (const item of vocabulary) lookup[`vocab:${item.id}`] = [item.kanji ? `${item.kanji}（${item.kana}）` : item.kana, `/vocabulary?level=${item.level}&item=${encodeURIComponent(item.id)}`]

const catalog = `// Generated by scripts/generate-learning-index.mjs. Do not edit by hand.\nimport type { Lesson } from "./lesson-types"\nimport type { KanaLevel } from "@/lib/learning-progress-types"\nimport { getNextCourseLesson } from "@/lib/lesson-skip"\nexport type LessonSummary = Omit<Lesson, "steps"> & { practiceCount: number }\nexport const STARTER_LESSONS: LessonSummary[] = [\n${summaries.map(s => `  ${JSON.stringify(s)},`).join("\n")}\n]\nexport const STARTER_LESSON_BY_ID = Object.fromEntries(STARTER_LESSONS.map(lesson => [lesson.id, lesson])) as Record<string, LessonSummary>\nexport function getNextLesson(completed: ReadonlySet<string>, kanaLevel?: KanaLevel | null) {\n  return getNextCourseLesson(STARTER_LESSONS, completed, kanaLevel)\n}\n`
const items = `// Generated by scripts/generate-learning-index.mjs. Do not edit by hand.\nexport const LEARNING_ITEM_INDEX: Record<string, [display: string, href: string]> = {\n${Object.entries(lookup).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join("\n")}\n}\n`
for (const [name, text] of [["lesson-catalog.ts", catalog], ["learning-item-index.ts", items]]) {
  const target = path.join(root, "src", "data", name)
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== text) throw new Error(`${name} is stale. Run npm run generate:index.`)
  } else fs.writeFileSync(target, text)
}
console.log(`Learning index verified: ${summaries.length} courses, ${Object.keys(lookup).length} items`)
