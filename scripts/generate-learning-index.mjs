import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { loadTsModule } from "../tests/unit/load-ts-module.mjs"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const { STARTER_LESSONS } = await loadTsModule("src/data/lessons.ts")
const { grammarData } = await loadTsModule("src/data/grammar-data.ts")
const { kanaData } = await loadTsModule("src/data/kana-data.ts")
const { PARTICLE_QUESTIONS } = await loadTsModule("src/lib/quiz-data.ts")
const { lessonStepToQuestion } = await loadTsModule("src/lib/lesson-session.ts")
const { grammarPracticeTemplateToQuestion } = await loadTsModule("src/lib/grammar-practice.ts")
const { buildMistakeId } = await loadTsModule("src/lib/mistake-notebook-model.ts")
const { contentFingerprint } = await loadTsModule("src/lib/content-fingerprint.ts")
const { normalizeAnswer } = await loadTsModule("src/lib/questions.ts")
const { LEGACY_QUESTION_VERSIONS } = await loadTsModule("src/data/legacy-question-versions.ts")
const { AUDIT_CORRECTION_RECHECKS } = await loadTsModule("src/data/audit-correction-rechecks.ts")
const { kanjiReadingVersion, EXTRA_WORD_READINGS } = await loadTsModule("src/lib/kanji-reading-question.ts")
const { COURSE_PHASES } = await loadTsModule("src/lib/course-phases.ts")
const vocabulary = []
for (const level of ["survival", "daily", "fluent"]) {
  const data = await loadTsModule(`src/data/vocabulary/${level}.ts`)
  vocabulary.push(...data[`${level}Vocab`])
}
const summaries = STARTER_LESSONS.map(({ steps, study, ...lesson }) => {
  void study // Keep full course text out of the shared client catalog.
  return { ...lesson, practiceCount: steps.filter(step => "itemId" in step).length }
})
const lookup = {}
for (const lesson of STARTER_LESSONS) {
  lookup[`lesson:${lesson.id}`] = [lesson.title, `/learn/${lesson.id}`]
  for (const step of lesson.steps) {
    if (!("itemId" in step)) continue
    const key = `${step.itemType}:${step.itemId}`
    lookup[key] ??= [step.answer || step.title, `/learn/${lesson.id}`]
  }
}
for (const point of Object.values(grammarData).flat()) lookup[`grammar:${point.id}`] = [point.title, `/grammar?level=${point.level}&item=${encodeURIComponent(point.id)}`]
for (const item of vocabulary) lookup[`vocab:${item.id}`] = [item.kanji ? `${item.kanji}（${item.kana}）` : item.kana, `/vocabulary?level=${item.level}&item=${encodeURIComponent(item.id)}`]

const lessonSlugs = STARTER_LESSONS.map(lesson => lesson.id)
const lessonSlugIndex = new Map(lessonSlugs.map((id, index) => [id, index]))
const vocabLevelCode = { survival: 0, daily: 1, fluent: 2 }
const compactLookup = {}
for (const [key, [display, href]] of Object.entries(lookup)) {
  if (key.startsWith("lesson:") && href === `/learn/${key.slice(7)}`) {
    compactLookup[key] = display
  } else if (key.startsWith("vocab:")) {
    const m = /^\/vocabulary\?level=(survival|daily|fluent)&item=(.+)$/.exec(href)
    if (m && m[2] === encodeURIComponent(key.slice(6))) compactLookup[key] = [display, vocabLevelCode[m[1]]]
    else compactLookup[key] = [display, href]
  } else if (key.startsWith("grammar:")) {
    const m = /^\/grammar\?level=([^&]+)&item=(.+)$/.exec(href)
    if (m && m[2] === encodeURIComponent(key.slice(8))) compactLookup[key] = [display, m[1]]
    else compactLookup[key] = [display, href]
  } else if (href.startsWith("/learn/") && lessonSlugIndex.has(href.slice(7))) {
    compactLookup[key] = [display, lessonSlugIndex.get(href.slice(7))]
  } else {
    compactLookup[key] = [display, href]
  }
}

const catalog = `// Generated by scripts/generate-learning-index.mjs. Do not edit by hand.\nimport type { Lesson } from "./lesson-types"\nimport type { KanaLevel } from "@/lib/learning-progress-types"\nimport { getNextCourseLesson } from "@/lib/lesson-skip"\nexport type LessonSummary = Omit<Lesson, "steps" | "study"> & { practiceCount: number }\nexport const STARTER_LESSONS: LessonSummary[] = [\n${summaries.map(s => `  ${JSON.stringify(s)},`).join("\n")}\n]\nexport const STARTER_LESSON_BY_ID = Object.fromEntries(STARTER_LESSONS.map(lesson => [lesson.id, lesson])) as Record<string, LessonSummary>\nexport function getNextLesson(completed: ReadonlySet<string>, kanaLevel?: KanaLevel | null, entryOrder = 1) {\n  return getNextCourseLesson(STARTER_LESSONS, completed, kanaLevel, entryOrder)\n}\n`
const items = `// Generated by scripts/generate-learning-index.mjs. Do not edit by hand.\nconst SLUGS=${JSON.stringify(lessonSlugs)}\nconst VLEVELS=["survival","daily","fluent"] as const\nconst RAW: Record<string, string | [string, number | string]> = ${JSON.stringify(compactLookup)}\nexport const LEARNING_ITEM_INDEX: Record<string, [display: string, href: string]> = Object.fromEntries(Object.entries(RAW).map(([k, v]) => {\n  if (typeof v === "string") return [k, [v, \`/learn/\${k.slice(7)}\`]]\n  const [d, t] = v\n  if (typeof t === "number") {\n    if (k.startsWith("vocab:")) return [k, [d, \`/vocabulary?level=\${VLEVELS[t]}&item=\${encodeURIComponent(k.slice(6))}\`]]\n    return [k, [d, \`/learn/\${SLUGS[t]}\`]]\n  }\n  if (k.startsWith("grammar:") && !t.startsWith("/")) return [k, [d, \`/grammar?level=\${t}&item=\${encodeURIComponent(k.slice(8))}\`]]\n  return [k, [d, t]]\n}))\n`
// Compact compatibility metadata keeps full lesson/vocabulary text out of the home bundle.
const reviewVersions = {}
for (const lesson of STARTER_LESSONS) {
  for (const step of lesson.steps.filter(step => "itemId" in step)) {
    const question = lessonStepToQuestion(step)
    const key = contentFingerprint(buildMistakeId(question))
    ;(reviewVersions[key] ??= []).push([question.questionVersion, LEGACY_QUESTION_VERSIONS.has(question.questionVersion), `/learn/${lesson.id}`])
  }
}
const grammarVersions = {}
for (const point of Object.values(grammarData).flat()) {
  for (const template of point.practiceTemplates ?? []) {
    const question = grammarPracticeTemplateToQuestion(point, template)
    if (question) grammarVersions[question.mistakeId] = [question.questionVersion, `/grammar?level=${point.level}&item=${encodeURIComponent(point.id)}`]
  }
}
const glossGroups = new Map()
for (const item of vocabulary) {
  const gloss = normalizeAnswer(item.meaning)
  if (!glossGroups.has(gloss)) glossGroups.set(gloss, [])
  glossGroups.get(gloss).push(item.id)
}
const ambiguousGlossGroups = [...glossGroups.entries()].filter(([, ids]) => ids.length > 1)
const affectedModes = {}
const affect = (type, id, mode) => {
  const key = `${type}:${id}`
  affectedModes[key] = [...new Set([...(affectedModes[key] ?? []), mode])]
}
for (const point of Object.values(grammarData).flat()) if (point.practiceTemplates?.length) affect("grammar", point.id, "recognition")
for (const lesson of STARTER_LESSONS) for (const step of lesson.steps.filter(step => "itemId" in step)) {
  if (step.title === "听音选择") affect(step.itemType, step.itemId, "listening")
  // Old mixed mistake review displayed stored explanations before submission.
  if (step.explanation) affect(step.itemType, step.itemId, step.mode === "production" ? "recognition" : step.mode)
  if (step.id === "d135-build") affect(step.itemType, step.itemId, "recall")
}
for (const [, ids] of ambiguousGlossGroups) for (const id of ids) affect("vocab", id, "recall")
// The old audio-kana mistake prompt printed the target glyph; any such listening aggregate may be affected.
for (const kana of kanaData) affect("kana", `hiragana:${kana.romaji}`, "listening")
for (const question of PARTICLE_QUESTIONS) affect("grammar", `particle:${question.answer}:${question.full}`, "recognition")
const recheckModes = {}
for (const entry of AUDIT_CORRECTION_RECHECKS) {
  affect(entry.itemType, entry.itemId, entry.mode)
  const key = `${entry.itemType}:${entry.itemId}`
  ;(recheckModes[key] ??= {})[entry.mode] ??= { revision: "", versions: [] }
}
const currentQuestions = [
  ...STARTER_LESSONS.flatMap(lesson => lesson.steps.filter(step => "itemId" in step).map(lessonStepToQuestion)),
  ...Object.values(grammarData).flat().flatMap(point => (point.practiceTemplates ?? []).map(template => grammarPracticeTemplateToQuestion(point, template))).filter(Boolean),
]
for (const question of currentQuestions) {
  const entry = recheckModes[`${question.itemType}:${question.itemId}`]?.[question.mode]
  if (entry && question.questionVersion) entry.versions.push(question.questionVersion)
}
for (const [key, modes] of Object.entries(recheckModes)) for (const [mode, entry] of Object.entries(modes)) {
  entry.versions = [...new Set(entry.versions)].sort()
  entry.revision = contentFingerprint([key, mode, entry.versions])
}
const affected = `// Generated by scripts/generate-learning-index.mjs. Audit sources F01-F05/F07.\nimport type { PracticeMode } from "@/lib/learning-progress-types"\nexport const AUDIT_AFFECTED_MODES: Record<string, PracticeMode[]> = ${JSON.stringify(affectedModes, null, 2)}\nexport const AUDIT_RECHECK_MODES: Record<string, Partial<Record<PracticeMode, { revision: string; versions: string[] }>>> = ${JSON.stringify(recheckModes, null, 2)}\n`
const compactReviewVersions = Object.fromEntries(
  Object.entries(reviewVersions).map(([k, rows]) => [
    k,
    rows.map(([ver, legacy, href]) => [ver, legacy ? 1 : 0, lessonSlugIndex.get(href.slice(7)) ?? href]),
  ])
)
const compactGrammarVersions = Object.fromEntries(
  Object.entries(grammarVersions).map(([k, [ver, href]]) => {
    const m = /^\/grammar\?level=([^&]+)&item=(.+)$/.exec(href)
    return [k, m ? [ver, m[1], decodeURIComponent(m[2])] : [ver, href]]
  })
)
const compatibility = `// Generated by scripts/generate-learning-index.mjs. Do not edit by hand.\nconst SLUGS=${JSON.stringify(lessonSlugs)}\nconst RAW_LESSON: Record<string, [string, 0 | 1, number | string][]> = ${JSON.stringify(compactReviewVersions)}\nconst RAW_GRAMMAR: Record<string, [string, string] | [string, string, string]> = ${JSON.stringify(compactGrammarVersions)}\nexport const LESSON_REVIEW_VERSIONS: Record<string, [version: string, legacyCompatible: boolean, href: string][]> = Object.fromEntries(Object.entries(RAW_LESSON).map(([k, rows]) => [k, rows.map(([v, l, h]) => [v, l === 1, typeof h === "number" ? \`/learn/\${SLUGS[h]}\` : h])]))\nexport const GRAMMAR_REVIEW_VERSIONS: Record<string, [version: string, href: string]> = Object.fromEntries(Object.entries(RAW_GRAMMAR).map(([k, row]) => [k, row.length === 3 ? [row[0], \`/grammar?level=\${row[1]}&item=\${encodeURIComponent(row[2])}\`] : [row[0], row[1]]]))\nexport const AMBIGUOUS_VOCAB_GLOSSES: [gloss: string, ids: string[]][] = ${JSON.stringify(ambiguousGlossGroups)}\n`
const assessmentSteps = Object.fromEntries(STARTER_LESSONS.map(lesson => [lesson.id,
  lesson.steps.filter(step => "itemId" in step).map(step => [step.id, lessonStepToQuestion(step).questionVersion])]))
const assessment = `// Generated by scripts/generate-learning-index.mjs. Do not edit by hand.\nexport const LESSON_ASSESSMENT_STEPS: Record<string, [stepId: string, version: string][]> = {\n${Object.entries(assessmentSteps).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join("\n")}\n}\n`
// Different authored comprehension questions may share exactly the same source.
// Keep reading and listening separate so a variant never changes the measured mode.
const materialGroups = new Map()
for (const lesson of STARTER_LESSONS) for (const step of lesson.steps) {
  if (step.type !== "multipleChoice" || step.itemType !== "sentence") continue
  const material = step.mode === "listening" ? step.audioText : step.passage
  if (!material) continue
  const key = contentFingerprint([step.mode, material])
  const questions = materialGroups.get(key) ?? new Map()
  const question = lessonStepToQuestion(step)
  questions.set(question.questionVersion, question)
  materialGroups.set(key, questions)
}
const families = Object.fromEntries([...materialGroups].filter(([, questions]) => questions.size > 1).map(([key, questions]) => [key, [...questions.values()]]))
const familiesByVersion = Object.fromEntries(Object.entries(families).flatMap(([key, questions]) => questions.map(question => [question.questionVersion, key])))
const grammarFamilies = Object.fromEntries(Object.values(grammarData).flat().filter(point => point.practiceTemplates?.length > 1)
  .map(point => [point.id, point.practiceTemplates.map(template => grammarPracticeTemplateToQuestion(point, template)).filter(Boolean)]))
const variants = `// Generated by scripts/generate-learning-index.mjs. Do not edit by hand.\nimport type { Question } from "@/lib/questions"\nexport const GRAMMAR_REVIEW_FAMILIES: Record<string, Question[]> = ${JSON.stringify(grammarFamilies)}\nexport const COMPREHENSION_REVIEW_FAMILIES: Record<string, Question[]> = ${JSON.stringify(families)}\nexport const COMPREHENSION_FAMILY_BY_VERSION: Record<string, string> = ${JSON.stringify(familiesByVersion)}\n`
const stageCoverage = {}
const stageKanji = {}
const kanjiRevisions = {}
for (const phase of COURSE_PHASES) {
  const lessons = STARTER_LESSONS.filter(lesson => lesson.track === phase.track)
  const ids = type => [...new Set(lessons.flatMap(lesson => lesson.newItemIds.filter(item => item.type === type).map(item => item.id)))]
  const vocabIds = new Set(ids("vocab"))
  const words = vocabulary.filter(word => vocabIds.has(word.id) && /\p{Script=Han}/u.test(word.kanji ?? ""))
  const questions = words.map(word => {
    const question = { id: word.id, word: word.kanji, reading: word.kana, acceptedReadings: EXTRA_WORD_READINGS[word.id] ?? [],
      meaning: word.id === "flu-biz-10" ? "市场（经济中的供求、交易范围）" : word.meaning }
    const version = kanjiReadingVersion(question)
    kanjiRevisions[word.id] = version
    return { ...question, version }
  })
  const steps = lessons.flatMap(lesson => lesson.steps)
  stageKanji[phase.id] = questions
  stageCoverage[phase.id] = { lessons: lessons.length, vocabulary: vocabIds.size, grammar: ids("grammar").length,
    kanjiWords: questions.length, uniqueKanji: new Set(words.flatMap(word => [...word.kanji].filter(char => /\p{Script=Han}/u.test(char)))).size,
    reading: steps.filter(step => step.type === "multipleChoice" && step.passage).length,
    listening: steps.filter(step => "itemId" in step && step.mode === "listening").length,
    input: steps.filter(step => step.type === "typing" && step.mode === "production").length }
}
const coverageText = `// Generated by scripts/generate-learning-index.mjs. Actual declared course coverage, not a JLPT syllabus.\nexport const STAGE_COVERAGE = ${JSON.stringify(stageCoverage, null, 2)}\nexport const STAGE_KANJI_REVISIONS: Record<string, string> = ${JSON.stringify(kanjiRevisions)}\n`
const kanjiText = `// Generated by scripts/generate-learning-index.mjs. Word-level readings from declared vocabulary.\nimport type { CoursePhaseId } from "@/lib/course-phases"\nimport type { KanjiReadingQuestion } from "@/lib/kanji-reading-question"\nexport const STAGE_KANJI: Record<CoursePhaseId, KanjiReadingQuestion[]> = ${JSON.stringify(stageKanji, null, 2)}\n`
for (const [name, text] of [["lesson-catalog.ts", catalog], ["learning-item-index.ts", items], ["review-compatibility-index.ts", compatibility], ["audit-affected-modes.ts", affected], ["lesson-assessment-index.ts", assessment], ["knowledge-review-variants.ts", variants], ["stage-coverage-index.ts", coverageText], ["stage-kanji.ts", kanjiText]]) {
  const target = path.join(root, "src", "data", name)
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== text) throw new Error(`${name} is stale. Run npm run generate:index.`)
  } else fs.writeFileSync(target, text)
}
console.log(`Learning index verified: ${summaries.length} courses, ${Object.keys(lookup).length} items`)
