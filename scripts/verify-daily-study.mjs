import assert from "node:assert/strict"
import { chromium } from "playwright"
import { loadTsModule } from "../tests/unit/load-ts-module.mjs"
const { STORAGE_KEYS } = await loadTsModule("src/lib/storage-keys.ts")
const { createSrsState } = await loadTsModule("src/lib/srs-model.ts")
const base = process.env.E2E_BASE_URL ?? "http://127.0.0.1:3218"
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ serviceWorkers: "block", viewport: { width: 390, height: 844 } })
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  await page.goto(base, { waitUntil: "networkidle" })
  await page.evaluate(({ keys, srs }) => {
    const ids = ["hiragana:a", "hiragana:i", "hiragana:u", "hiragana:e"]
    localStorage.setItem(keys.KANA_MASTERED, JSON.stringify(ids))
    localStorage.setItem(keys.SRS_KANA, JSON.stringify(Object.fromEntries(ids.map(id => [id, srs]))))
    localStorage.setItem(keys.USER_PROFILE, JSON.stringify({ goal: "travel", minutesPerDay: 10, kanaLevel: "none", romajiMode: "practice", createdAt: 1, updatedAt: 1 }))
  }, { keys: STORAGE_KEYS, srs: { ...createSrsState(1), dueAt: 1 } })
  await page.reload({ waitUntil: "networkidle" })
  const plan = page.getByTestId("daily-study-plan")
  assert.match(await plan.innerText(), /10 分钟预算/)
  assert.equal(await plan.locator("[data-daily-task]").count(), 3)
  await plan.getByTestId("daily-plan-start").click()
  await plan.getByTestId("daily-task-progress").waitFor()
  assert.match(await plan.getByTestId("daily-task-progress").innerText(), /主要任务 0\/2/)
  await plan.locator('[data-daily-task="reading"]').getByRole("checkbox").check()
  await page.waitForFunction(key => Object.values(JSON.parse(localStorage.getItem(key) ?? "{}")).some(plan => plan.tasks.some(task => task.kind === "reading" && task.confirmedAt)), STORAGE_KEYS.DAILY_STUDY_PLANS)
  await page.reload({ waitUntil: "networkidle" })
  assert.equal(await plan.getByRole("checkbox").isChecked(), true)
  assert.match(await plan.getByTestId("daily-task-progress").innerText(), /主要任务 1\/2/)
  await plan.locator('[data-daily-task="review"]').getByRole("link").click()
  await page.getByTestId("review-budget-notice").waitFor()
  assert.match(await page.getByTestId("review-budget-notice").innerText(), /最多 2 题/)
  await page.getByTestId("review-start-today").click()
  for (let i = 0; i < 2; i++) {
    const prompt = await page.locator(".font-jp.text-4xl").innerText()
    const correct = { "あ": "a", "い": "i", "う": "u", "え": "e" }[prompt]
    assert.ok(correct)
    await page.locator(`[data-testid^="review-answer-"]:not([data-testid="review-answer-${correct}"])`).first().click()
    await page.getByTestId("review-next").click()
  }
  await page.getByTestId("review-complete-state").waitFor()
  assert.match(await page.getByTestId("review-complete-state").innerText(), /共作答 2 次：答对 0 次/)
  const reviewed = await page.evaluate(key => Object.values(JSON.parse(localStorage.getItem(key))), STORAGE_KEYS.SRS_KANA)
  assert.equal(reviewed.filter(state => state.wrong === 1 && state.box === 0).length, 2)
  const calendar = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), STORAGE_KEYS.STUDY_CALENDAR)
  assert.ok(Object.values(calendar).some(day => day.reviewCount === 2 && day.practiceCount === 2))
  await page.goto(base, { waitUntil: "networkidle" })
  assert.match(await plan.getByTestId("daily-task-progress").innerText(), /主要任务 2\/2/)
  await plan.locator('[data-daily-task="writing"]').getByRole("link").click()
  await page.waitForURL(`${base}/practice/travel-order`)
  const editor = page.getByTestId("written-work")
  await editor.getByRole("textbox").fill("メニューをお願いします。コーヒーを二杯お願いします。お会計をお願いします。")
  for (let i = 0; i < 2; i++) {
    await editor.getByRole("checkbox").nth(i).check()
    await page.waitForFunction(({ key, count }) => Object.values(JSON.parse(localStorage.getItem(key) ?? "{}")).some(work => work.checked.length === count), { key: STORAGE_KEYS.WRITTEN_WORKS, count: i + 1 })
  }
  await editor.getByTestId("work-complete").click()
  await editor.getByText("已保存 · 已完成自查（本人确认）", { exact: true }).waitFor()
  await page.goto(base, { waitUntil: "networkidle" })
  assert.match(await plan.locator('[data-daily-task="writing"]').innerText(), /已完成作品自查/)
  await page.getByTestId("home-edit-profile").click()
  await page.getByTestId("onboarding-goal-media").click()
  await page.getByTestId("onboarding-minutes").focus()
  await page.getByTestId("onboarding-minutes").press("End")
  await page.getByTestId("onboarding-save").click()
  await page.getByRole("dialog").waitFor({ state: "hidden" })
  assert.match(await plan.innerText(), /10 分钟预算/)
  await plan.getByText("调整今天的安排", { exact: true }).click()
  await plan.getByTestId("daily-plan-start").click()
  await page.waitForFunction(key => Object.keys(JSON.parse(localStorage.getItem(key) ?? "{}")).length === 2, STORAGE_KEYS.DAILY_STUDY_PLANS)
  assert.match(await plan.innerText(), /20 分钟预算/)
  assert.equal(await plan.locator('[data-daily-task="writing"]').getByRole("link").getAttribute("href"), "/practice/media-address")
  const plans = await page.evaluate(key => Object.values(JSON.parse(localStorage.getItem(key))), STORAGE_KEYS.DAILY_STUDY_PLANS)
  assert.ok(plans.find(plan => plan.minutes === 10).tasks.find(task => task.kind === "reading").confirmedAt)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await page.evaluate(key => localStorage.setItem(key, '{"broken":true}'), STORAGE_KEYS.DAILY_STUDY_PLANS)
  await page.reload({ waitUntil: "networkidle" })
  await plan.getByRole("alert").waitFor()
  assert.equal(await plan.getByTestId("daily-plan-start").isDisabled(), true)
  assert.equal(await page.evaluate(key => localStorage.getItem(key), STORAGE_KEYS.DAILY_STUDY_PLANS), '{"broken":true}')
  assert.deepEqual(errors, [])
  console.log("Daily study passed: bounded review, actual graded counts, reading confirmation, saved work, stable plans, replanning archive, reload and corrupt-data protection.")
} finally { await browser.close() }
