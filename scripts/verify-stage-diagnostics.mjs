import assert from "node:assert/strict"
import { chromium } from "playwright"
import fs from "node:fs/promises"
import { loadTsModule } from "../tests/unit/load-ts-module.mjs"
const { STAGE_DIAGNOSTICS } = await loadTsModule("src/data/stage-diagnostics.ts")
const model = await loadTsModule("src/lib/stage-diagnostic-model.ts")
const { STARTER_LESSONS } = await loadTsModule("src/data/lesson-catalog.ts")
const { STORAGE_KEYS, LEARNING_WRITE_EPOCH_KEY } = await loadTsModule("src/lib/storage-keys.ts")
const { LEARNING_WRITE_LOCK_NAME } = await loadTsModule("src/lib/learning-write-lock.ts")
const base = process.env.E2E_BASE_URL ?? "http://127.0.0.1:3218"
const browser = await chromium.launch({ headless: true })
try {
  const context = await browser.newContext({ serviceWorkers: "block", viewport: { width: 390, height: 844 } })
  // Deterministic playback lifecycle only; this does not test a real OS voice.
  await context.addInitScript(() => {
    let timer
    Object.defineProperty(window, "SpeechSynthesisUtterance", { value: class { constructor(text) { this.text = text } }, configurable: true })
    Object.defineProperty(window, "speechSynthesis", { value: { getVoices: () => [{ lang: "ja-JP", name: "Test voice" }], cancel: () => clearTimeout(timer), speak: utterance => { utterance.onstart?.(); timer = setTimeout(() => utterance.onend?.(), 20) } }, configurable: true })
  })
  const page = await context.newPage()
  page.setDefaultTimeout(45000)
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key) ?? '{"attempts":{}}'), STORAGE_KEYS.DIAGNOSTICS)
  await page.goto(`${base}/placement/n5`, { waitUntil: "networkidle" })
  await page.getByRole("button", { name: "开始本阶段诊断", exact: true }).click()
  for (let index = 0; index < STAGE_DIAGNOSTICS.n5.length; index++) {
    const q = STAGE_DIAGNOSTICS.n5[index]
    await page.getByRole("heading", { name: q.prompt, exact: true }).waitFor()
    assert.equal(await page.getByText("查看逐题答案与解析", { exact: true }).count(), 0)
    if (q.audio) {
      assert.equal(await page.getByTestId("diagnostic-transcript").count(), 0)
      assert.doesNotMatch(await page.getByTestId("diagnostic-audio").innerText(), new RegExp(q.audio.split("\n")[0]))
      await page.getByRole("button", { name: "播放材料", exact: true }).click()
      await page.getByText("本段已完整播放，可以重听。", { exact: true }).waitFor()
    }
    if (q.readingInput) await page.getByRole("textbox", { name: "完整假名读音" }).fill(q.answer)
    else await page.getByRole("radio", { name: q.answer, exact: true }).check()
    if (index === 0) {
      assert.equal(await page.getByRole("textbox", { name: "完整假名读音" }).evaluate(input => input.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", keyCode: 229, isComposing: true, bubbles: true, cancelable: true }))), false)
      assert.equal(Object.keys(Object.values((await read()).attempts)[0].answers).length, 0)
    }
    await page.getByRole("button", { name: "确认并继续", exact: true }).click()
    await page.waitForFunction(({ key, count }) => Object.values(JSON.parse(localStorage.getItem(key)).attempts).some(a => Object.keys(a.answers).length === count), { key: STORAGE_KEYS.DIAGNOSTICS, count: index + 1 })
    if (index === 2) await page.reload({ waitUntil: "networkidle" })
  }
  await page.getByTestId("diagnostic-result").waitFor()
  assert.match(await page.getByTestId("diagnostic-result").innerText(), /16\/16（100%）/)
  await page.getByRole("button", { name: "采用第 46 课为起点", exact: true }).click()
  await page.getByRole("button", { name: "已采用本轮定位", exact: true }).waitFor()
  assert.equal(model.getDiagnosticEntryOrder(await read()), 46)
  assert.equal(await page.evaluate(key => localStorage.getItem(key), STORAGE_KEYS.LESSON_PROGRESS), null)
  const adopted = await read()
  await page.goto(`${base}/settings`, { waitUntil: "networkidle" })
  const [download] = await Promise.all([page.waitForEvent("download"), page.getByTestId("learning-data-export").click()])
  const backup = JSON.parse(await fs.readFile(await download.path(), "utf8"))
  assert.deepEqual(JSON.parse(backup.entries[STORAGE_KEYS.DIAGNOSTICS]), adopted)
  await page.getByTestId("learning-data-reset").click()
  await page.getByTestId("learning-data-reset-dialog-confirm").click()
  await page.waitForFunction(key => localStorage.getItem(key) === null, STORAGE_KEYS.DIAGNOSTICS)
  const chooserPromise = page.waitForEvent("filechooser")
  await page.getByTestId("learning-data-import").click()
  await (await chooserPromise).setFiles({ name: "diagnostics-v8.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(backup)) })
  await page.getByTestId("learning-data-restore-dialog-confirm").click()
  await page.waitForFunction(({ key, id }) => JSON.parse(localStorage.getItem(key) ?? "{}").entryAttemptId === id, { key: STORAGE_KEYS.DIAGNOSTICS, id: adopted.entryAttemptId })
  assert.deepEqual(await read(), adopted)
  await page.goto(`${base}/path`, { waitUntil: "networkidle" })
  assert.equal(await page.getByTestId("path-course-phase-n4").getAttribute("aria-expanded"), "true")
  assert.match(await page.locator("main").innerText(), /已完成 0\/175/)
  assert.ok(await page.locator(`a[href="/learn/${STARTER_LESSONS[45].id}"]`).count())
  assert.equal(await page.locator(`a[href="/learn/${STARTER_LESSONS[46].id}"]`).count(), 0)
  await page.goto(base, { waitUntil: "networkidle" })
  assert.match(await page.locator("main").innerText(), /第 46 课/)
  await page.goto(`${base}/learn/${STARTER_LESSONS[45].id}`, { waitUntil: "networkidle" })
  await page.waitForFunction(({ key, id }) => JSON.parse(localStorage.getItem(key) ?? "{}")[id]?.status === "started", { key: STORAGE_KEYS.LESSON_PROGRESS, id: STARTER_LESSONS[45].id })
  await page.goto(`${base}/placement`, { waitUntil: "networkidle" })
  await page.getByRole("button", { name: "撤销诊断定位，恢复按基础推荐", exact: true }).click()
  await page.getByText("当前未采用诊断跳级", { exact: true }).waitFor()
  assert.equal(Object.keys((await read()).attempts).length, 1)
  await page.goto(`${base}/path`, { waitUntil: "networkidle" })
  assert.equal(await page.locator(`a[href="/learn/${STARTER_LESSONS[45].id}"]`).count(), 0)
  await page.goto(`${base}/placement/n5`, { waitUntil: "networkidle" })
  await page.getByRole("button", { name: "开始新一轮（已见材料）", exact: true }).click()
  for (const q of STAGE_DIAGNOSTICS.n5) {
    await page.getByRole("heading", { name: q.prompt, exact: true }).waitFor()
    if (q.audio && q.id.endsWith("2")) await page.getByRole("button", { name: "看文字辅助（本段不计独立听力）", exact: true }).click()
    if (q.audio && q.id.endsWith("2")) await page.getByTestId("diagnostic-transcript").waitFor()
    if (q.readingInput) await page.getByRole("textbox", { name: "完整假名读音" }).fill(q.answer)
    else await page.getByRole("radio", { name: q.answer, exact: true }).check()
    await page.getByRole("button", { name: "确认并继续", exact: true }).click()
  }
  await page.getByTestId("diagnostic-result").waitFor()
  assert.match(await page.getByTestId("diagnostic-result").innerText(), /12\/16（75%）/)
  assert.equal(await page.getByRole("button", { name: "采用第 46 课为起点", exact: true }).count(), 0)
  assert.equal(model.getDiagnosticEntryOrder(await read()), 1)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo({ top: 0, left: 0, behavior: "instant" }) })
  await page.waitForFunction(() => window.scrollY === 0)
  await page.screenshot({ path: "output/d08-diagnostic-mobile.png", fullPage: true })
  // A reset while a new attempt is queued cannot revive old-page work.
  await page.evaluate(name => { void navigator.locks.request(name, () => new Promise(resolve => { window.releaseDiagnosticLock = resolve })) }, LEARNING_WRITE_LOCK_NAME)
  await page.waitForFunction(() => typeof window.releaseDiagnosticLock === "function")
  await page.getByRole("button", { name: "开始新一轮（已见材料）", exact: true }).click()
  await page.evaluate(({ key, epoch }) => { localStorage.removeItem(key); localStorage.setItem(epoch, crypto.randomUUID()); window.releaseDiagnosticLock() }, { key: STORAGE_KEYS.DIAGNOSTICS, epoch: LEARNING_WRITE_EPOCH_KEY })
  await page.getByText("保存失败或记录已在另一页面改变。当前输入仍在，请检查记录后重试；本次未计入。", { exact: true }).waitFor()
  assert.equal(await page.evaluate(key => localStorage.getItem(key), STORAGE_KEYS.DIAGNOSTICS), null)
  await page.evaluate(key => localStorage.setItem(key, "{broken"), STORAGE_KEYS.DIAGNOSTICS)
  await page.reload({ waitUntil: "networkidle" })
  await page.getByText(/诊断记录无法读取，已暂停保存/).waitFor()
  assert.equal(await page.getByRole("button", { name: "开始本阶段诊断", exact: true }).count(), 0)
  assert.equal(await page.evaluate(key => localStorage.getItem(key), STORAGE_KEYS.DIAGNOSTICS), "{broken")
  assert.deepEqual(errors, [])
  console.log("Stage diagnostics passed: 16 real submissions, playback callback gating, refresh, explicit placement across home/path/course, revoke without fake completions, assisted/absent audio failure, queued reset, corruption preservation and mobile layout. Voice playback was mocked.")
} finally { await browser.close() }
