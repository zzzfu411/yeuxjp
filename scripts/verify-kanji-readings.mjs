import assert from "node:assert/strict"
import { chromium } from "playwright"
import { loadTsModule } from "../tests/unit/load-ts-module.mjs"
const { STAGE_KANJI } = await loadTsModule("src/data/stage-kanji.ts")
const { STORAGE_KEYS } = await loadTsModule("src/lib/storage-keys.ts")
const { kanjiReadingKey } = await loadTsModule("src/lib/kanji-reading-question.ts")
const base = process.env.E2E_BASE_URL ?? "http://127.0.0.1:3218"
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ serviceWorkers: "block", viewport: { width: 390, height: 844 } })
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  await page.goto(`${base}/checkpoints/n5/kanji`, { waitUntil: "networkidle" })
  await page.evaluate(({ key, ids }) => localStorage.setItem(key, JSON.stringify(ids)), { key: STORAGE_KEYS.VOCAB_LEARNED, ids: STAGE_KANJI.n5.map(q => q.id) })
  await page.reload({ waitUntil: "networkidle" })
  assert.match(await page.getByTestId("kanji-status").innerText(), new RegExp(`未测 ${STAGE_KANJI.n5.length}`))
  await page.getByRole("button", { name: "练未测词", exact: true }).click()
  const word = await page.getByTestId("kanji-word").innerText()
  const meaning = await page.getByTestId("kanji-question").locator("p.text-lg").innerText()
  const question = STAGE_KANJI.n5.find(q => q.word === word && q.meaning === meaning)
  assert.ok(question)
  assert.doesNotMatch(await page.getByTestId("kanji-question").innerText(), new RegExp(question.reading))
  await page.getByRole("textbox", { name: "假名读音", exact: true }).fill("まちがい")
  assert.equal(await page.getByRole("textbox", { name: "假名读音", exact: true }).evaluate(input => input.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", keyCode: 229, isComposing: true, bubbles: true, cancelable: true }))), false)
  await page.getByRole("button", { name: "检查读音", exact: true }).click()
  await page.getByTestId("kanji-feedback").waitFor()
  assert.match(await page.getByTestId("kanji-feedback").innerText(), /本次未匹配/)
  await page.getByRole("button", { name: "结束本轮", exact: true }).click()
  await page.reload({ waitUntil: "networkidle" })
  assert.match(await page.getByTestId("kanji-status").innerText(), /需练 1 · 最近答对 0 · 到期 1/)
  await page.goto(`${base}/review`, { waitUntil: "networkidle" })
  assert.match(await page.getByTestId("kanji-review-notice").innerText(), /1 词到期/)
  await page.goto(`${base}/checkpoints/n5/kanji`, { waitUntil: "networkidle" })
  await page.getByRole("button", { name: "复习到期词", exact: true }).click()
  assert.equal(await page.getByTestId("kanji-word").innerText(), question.word)
  await page.getByRole("textbox", { name: "假名读音", exact: true }).fill(question.reading)
  await page.getByRole("button", { name: "检查读音", exact: true }).click()
  await page.getByTestId("kanji-feedback").waitFor()
  assert.match(await page.getByTestId("kanji-feedback").innerText(), /本次读音答对/)
  const saved = await page.evaluate(({ key, items, results, id, card }) => ({ reading: JSON.parse(localStorage.getItem(key))[card], item: JSON.parse(localStorage.getItem(items))[id], results: JSON.parse(localStorage.getItem(results)) }), { key: STORAGE_KEYS.KANJI_READINGS, items: STORAGE_KEYS.ITEM_PROGRESS, results: STORAGE_KEYS.PRACTICE_RESULTS, id: question.id, card: kanjiReadingKey(question) })
  assert.equal(saved.reading.srs.right, 1); assert.equal(saved.reading.srs.wrong, 1)
  assert.ok(saved.reading.srs.dueAt > Date.now())
  assert.equal(saved.item.outputEvidence, undefined)
  assert.equal(saved.results.filter(r => r.itemId === question.id && r.activitySource === "review").length, 1)
  await page.getByRole("button", { name: "下一词", exact: true }).click()
  await page.getByTestId("kanji-round-end").waitFor()
  await page.getByRole("button", { name: "返回集合", exact: true }).click()
  assert.match(await page.getByTestId("kanji-status").innerText(), /需练 0 · 最近答对 1 · 到期 0/)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0) })
  await page.screenshot({ path: "output/d08-kanji-mobile.png", fullPage: true })
  await page.evaluate(key => localStorage.setItem(key, "[]"), STORAGE_KEYS.KANJI_READINGS)
  await page.reload({ waitUntil: "networkidle" })
  await page.getByText(/读音记录无法读取，已暂停保存/).waitFor()
  assert.equal(await page.evaluate(key => localStorage.getItem(key), STORAGE_KEYS.KANJI_READINGS), "[]")
  assert.deepEqual(errors, [])
  console.log("Kanji readings passed: word-card self-ratings do not count, actual wrong and correct typing, persisted separate SRS, due-only round, practice history without production inflation, mobile layout and corruption preservation.")
} finally { await browser.close() }
