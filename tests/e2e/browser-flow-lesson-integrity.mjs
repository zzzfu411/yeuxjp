import assert from "node:assert/strict"
import { readJsonStorage } from "./harness.mjs"
import { E2E_STORAGE_KEYS } from "./storage-keys.mjs"

export async function verifyLessonIntegrity(page, baseUrl) {
  const url = `${baseUrl}/learn/day-1-a-row-hello`
  const lessonId = "day-1-a-row-hello"
  await page.goto(baseUrl, { waitUntil: "networkidle" })
  await page.evaluate(() => localStorage.clear())
  await page.goto(url, { waitUntil: "networkidle" })
  await page.getByTestId("lesson-next").click()
  await page.getByTestId("lesson-next").click()
  const choices = page.locator('[data-testid^="lesson-answer-"]')
  const order = await choices.allTextContents()
  await page.reload({ waitUntil: "networkidle" })
  assert.deepEqual(await choices.allTextContents(), order, "refresh must not reshuffle this attempt")
  await page.getByTestId("lesson-answer-a").click()
  await page.getByTestId("lesson-next").click()
  await page.getByRole("button", { name: "お", exact: true }).click()
  await page.getByTestId("lesson-next").click()
  const input = page.getByTestId("lesson-typing-input")
  assert.equal(await page.locator('[data-testid="lesson-hint-content"]').count(), 0)
  await input.fill("こんにち")
  const before = await readJsonStorage(page, E2E_STORAGE_KEYS.PRACTICE_RESULTS)
  await input.dispatchEvent("compositionstart")
  await input.dispatchEvent("keydown", { key: "Enter", code: "Enter", isComposing: true, bubbles: true })
  assert.equal(await input.isDisabled(), false, "IME candidate confirmation must not submit")
  assert.deepEqual(await readJsonStorage(page, E2E_STORAGE_KEYS.PRACTICE_RESULTS), before)
  await input.dispatchEvent("compositionend")
  await page.getByRole("button", { name: "查看提示（不计入独立答对）", exact: true }).click()
  await page.locator('[data-testid="lesson-hint-content"]').waitFor()
  await page.reload({ waitUntil: "networkidle" })
  await page.locator('[data-testid="lesson-hint-content"]').waitFor()
  await input.fill("こんにちは")
  await input.press("Enter")
  await page.waitForFunction(() => document.querySelector('[data-testid="lesson-typing-input"]').disabled)
  const assisted = (await readJsonStorage(page, E2E_STORAGE_KEYS.PRACTICE_RESULTS)).at(-1)
  assert.equal(assisted.assisted, true)
  assert.equal(assisted.correct, true)
  assert.equal((await readJsonStorage(page, E2E_STORAGE_KEYS.ITEM_PROGRESS))["sur-g-1"].recall, 0)
  assert.equal((await readJsonStorage(page, E2E_STORAGE_KEYS.SRS_VOCAB))?.["sur-g-1"], undefined)
  await page.getByTestId("lesson-next").click()
  await page.getByTestId("lesson-next").click()
  await page.getByTestId("lesson-completed-summary").waitFor()
  const first = (await readJsonStorage(page, E2E_STORAGE_KEYS.LESSON_PROGRESS))[lessonId]
  assert.equal(first.score, 67)
  await page.getByRole("button", { name: "重新练习本课", exact: true }).click()
  await page.getByRole("heading", { name: "先抓住日语的元音", exact: true }).waitFor()
  await page.reload({ waitUntil: "networkidle" })
  await page.getByRole("heading", { name: "先抓住日语的元音", exact: true }).waitFor()
  const restarted = (await readJsonStorage(page, E2E_STORAGE_KEYS.LESSON_PROGRESS))[lessonId]
  assert.equal(restarted.completedAt, first.completedAt)
  assert.equal(restarted.score, first.score)
  assert.ok(restarted.attemptId)
  await page.getByTestId("lesson-next").click()
  await page.getByTestId("lesson-next").click()
  assert.equal(await page.getByTestId("lesson-answer-a").isEnabled(), true, "new attempt must not restore old locked answers")
  await page.getByTestId("lesson-answer-a").click()
  await page.getByTestId("lesson-next").and(page.locator(":enabled")).waitFor({ state: "visible" })
  const repeated = (await readJsonStorage(page, E2E_STORAGE_KEYS.PRACTICE_RESULTS)).filter(r => r.lessonStepId === "recognize-a")
  assert.equal(repeated.length, 2)
  assert.equal(repeated[1].lessonAttemptId, restarted.attemptId)
  await page.evaluate(() => localStorage.clear())
}
