test("KanaControls owns kana mode tabs, set tabs, filters, and progress controls", () => {
  const source = read("src/components/kana/kana-controls.tsx")

  assert.match(source, /export function KanaControls/)
  assert.match(source, /onModeChange\("hiragana"\)/)
  assert.match(source, /onModeChange\("katakana"\)/)
  assert.match(source, /aria-pressed=\{mode === "hiragana"\}/)
  assert.match(source, /aria-pressed=\{mode === "katakana"\}/)
  assert.match(source, /data-testid="kana-mode-hiragana"/)
  assert.match(source, /data-testid="kana-mode-katakana"/)
  assert.match(source, /onKanaSetChange\(set\.id\)/)
  assert.match(source, /aria-pressed=\{kanaSet === set\.id\}/)
  assert.match(source, /data-testid=\{`kana-set-\$\{set\.id\}`\}/)
  assert.match(source, /onToggleRomaji/)
  assert.match(source, /aria-pressed=\{showRomaji\}/)
  assert.match(source, /data-testid="kana-romaji-toggle"/)
  assert.match(source, /onToggleOnlyUnmastered/)
  assert.match(source, /aria-pressed=\{onlyUnmastered\}/)
  assert.match(source, /data-testid="kana-only-unmastered-toggle"/)
  assert.match(source, /onClearMastered/)
  assert.match(source, /type="button"/)
  assert.match(source, /data-testid="kana-clear-progress"/)
  assert.match(source, /hover:bg-destructive\/10/)
  assert.match(source, /progress\.learned/)
  assert.match(source, /progress\.total/)
  assert.doesNotMatch(source, /Progress:/)
  assert.match(source, /<EyeOff/)
  assert.match(source, /<GlossaryButton/)
})
