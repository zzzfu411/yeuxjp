  assert.match(source, /export function KanaSetHint/)
  assert.match(source, /kanaSet: KanaSet/)
  assert.match(source, /kanaSet === "seion"/)
  assert.match(source, /kanaSet === "dakuon"/)
  assert.match(source, /kanaSet === "yoon"/)
  assert.match(source, /kanaSet === "special"/)
  assert.match(source, /termId="seion"/)
