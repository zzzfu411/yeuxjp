export function diagnosticVersion(phase: CoursePhaseId) {
  return diagnosticSnapshotVersion(DIAGNOSTIC_RULES, STAGE_DIAGNOSTICS[phase])
}

export function diagnosticSnapshotVersion(rules: { totalPercent: number; domainPercent: number; questionCount: number; kanjiMinimum: number }, questions: readonly DiagnosticQuestion[]) {
  // JSON object property order must not invalidate an exported/imported attempt.
  return contentFingerprint([
    [rules.totalPercent, rules.domainPercent, rules.questionCount, rules.kanjiMinimum],
    questions.map(q => [q.id, q.domain, q.prompt, q.answer, q.options, q.explanation, q.passage ?? null, q.audio ?? null, q.readingInput ?? false]),
  ])
}
